using System;
using UnityEngine;

[Serializable]
public class Resource
{
    public float strength; // resistance to breaking
    public float hardness; // resistance to deforming
    public float elasticity; // stretchiness
    public float ductility; // ability to deform without shattering
    public float thermalConductivity;
    public float electricConductivity;
    public float density;
    public float meltingPoint;
    public float reactivity;
    public float radioactivity;
}
